DY = 55  # sketch -> world offset for cat-relative typography

FONTS = """
      @font-face { font-family: "Fraunces"; src: url("assets/fonts/Fraunces-latin-var.woff2") format("woff2"); font-weight: 100 900; }
      @font-face { font-family: "Caveat"; src: url("assets/fonts/Caveat-latin-var.woff2") format("woff2"); font-weight: 400 700; }
      @font-face { font-family: "Space Mono"; src: url("assets/fonts/SpaceMono-Regular.woff2") format("woff2"); font-weight: 400; }
      @font-face { font-family: "Space Mono"; src: url("assets/fonts/SpaceMono-Bold.woff2") format("woff2"); font-weight: 700; }"""


def T(x, y, s, size, family="d", anchor="start", fill=INK, extra=""):
    fam = {
        "d": 'font-family="Fraunces" font-weight="900"',
        "d7": 'font-family="Fraunces" font-weight="700"',
        "di": 'font-family="Fraunces" font-weight="700" font-style="italic"',
        "h": 'font-family="Caveat" font-weight="700"',
        "m": 'font-family="Space Mono" font-weight="700" letter-spacing="4"',
    }[family]
    return f'<text x="{x}" y="{y}" {fam} font-size="{size}" text-anchor="{anchor}" fill="{fill}" {extra}>{s}</text>'


class Comp:
    def __init__(self, cid, phase, slug, default_dur):
        self.cid, self.phase, self.slug, self.dur = cid, phase, slug, default_dur
        self.layers = []

    def L(self, name, inner, ox=540, oy=960, wrap=None, style=""):
        el = (
            f'<div class="L" id="{self.cid}-{name}" data-layout-allow-overlap style="transform-origin:{ox}px {oy}px;{style}">'
            f'<svg viewBox="0 0 1080 1920">{inner}</svg></div>'
        )
        self.layers.append(el)
        return el

    def html(self, js):
        c = self.cid
        return f"""<!doctype html>
<html lang="id">
  <head>
    <meta charset="UTF-8" />
    <!-- Generated by build-phases.py — phase {self.phase}: {self.slug}. Edit the generator, not this file. -->
  </head>
  <body>
    <template>
      <style>{FONTS}
        #{c}-root {{
          position: absolute;
          inset: 0;
          perspective: 1400px;
          perspective-origin: 540px 960px;
        }}
        #{c}-root .L {{
          position: absolute;
          left: 0;
          top: 0;
          width: 1080px;
          height: 1920px;
        }}
        #{c}-root .L svg {{
          display: block;
          width: 100%;
          height: 100%;
          overflow: visible;
        }}
        #{c}-root .shadow {{
          filter: drop-shadow(10px 16px 0 rgba(43, 76, 126, 0.18));
        }}
      </style>

      <div id="{c}-root" data-composition-id="{c}" data-width="1080" data-height="1920">
        {"".join(self.layers)}
      </div>

      <script>
        (function () {{
          const CID = "{c}";
          const $ = (n) => document.getElementById(CID + "-" + n);
          // the script's document is scoped to this composition: walk up to our own clip in index.html
          const anyEl = document.querySelector("#{c}-root .L") || document.querySelector(".L");
          const host = anyEl ? anyEl.closest("[data-phase]") : null;
          const D = host ? parseFloat(host.getAttribute("data-duration")) : {self.dur};
          const X = Math.max(D - 0.75, 1.2); // exit: fold away before the camera leaves
          const tl = gsap.timeline({{ paused: true }});
          function popIn(el, t, d) {{
            tl.fromTo(el, {{ rotationX: -95, opacity: 0 }}, {{ rotationX: 0, opacity: 1, duration: d || 0.6, ease: "back.out(1.7)" }}, t);
          }}
          function write(el, t, d, x0, x1) {{
            tl.fromTo(
              el,
              {{ clipPath: `inset(0px ${{1080 - x0}}px 0px 0px)` }},
              {{ clipPath: `inset(0px ${{Math.max(0, 1080 - x1)}}px 0px 0px)`, duration: d, ease: "power1.inOut" }},
              t,
            );
          }}
          function foldOut(els, t) {{
            tl.to(els, {{ rotationX: 95, opacity: 0, duration: 0.35, ease: "power2.in", stagger: 0.03 }}, t);
          }}
{js}
          tl.seek(tl.duration(), true).seek(0, true);
          window.__timelines[CID] = tl;
        }})();
      </script>
    </template>
  </body>
</html>
"""


