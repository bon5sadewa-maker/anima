#!/usr/bin/env python3
"""Generate the nine phase typography compositions (compositions/pNN-*.html).

Each phase is a Studio clip in index.html. Its typography is laid out from the
locked storyboard v2 (screen coords, 1080x1920) and shifted onto where Romeow
actually stands in the 3D world (his feet sit on the ring at y 1333, ~55 px lower
than in the sketches). Every animation is timed from the clip's own start, and the
exit is keyed to the clip's duration, so retiming a clip in Studio keeps it intact.
"""
import pathlib

